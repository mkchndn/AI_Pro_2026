# 5. CONTEXT INSTANTIATION PIPELINE
# ==========================================
def load_llm(provider_name: str, model: str, key: str):
    """Instantiates the specific provider LLM architecture class based on selected settings."""
    if provider_name == "Google Gemini":
        return ChatGoogleGenerativeAI(
            model=model, google_api_key=key, temperature=0
        )
    elif provider_name == "Groq":
        return ChatGroq(
            model=model, api_key=key, temperature=0
        )


