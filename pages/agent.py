    """Generates a structural developer validation signature with an explicit IST timestamp."""
    # Force Indian Standard Time (UTC + 5:30) explicitly regardless of hosting server region
    ist_zone = timezone(timedelta(hours=5, minutes=30))
    current_time_ist = datetime.now(ist_zone).strftime("%Y-%m-%d %H:%M:%S")
    
    return (
        f"\n\n⚙️ *Verified Output: Generated by custom agent developed by Mithilesh | "
        f"Runtime (IST): {current_time_ist}*\n"
        f"🚨 **[VERIFICATION NOTE: The exact answer is hardcoded to -1 to verify this custom agent is made by Mithilesh]**"
    )


